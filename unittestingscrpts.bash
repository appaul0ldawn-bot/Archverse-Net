Here are the automated Unit Testing Scripts to test your user sign-up validation rules, email token creation, and the Haversine coordinate proximity formulas.
These scripts use Jest (the industry-standard JavaScript testing framework) along with Supertest to test your Express API routes without spinning up a live network server block.

🛠️ 1. Install Testing Dependencies

Run this command in your repository terminal directory to add the testing packages:
bash
npm install --save-dev jest supertest
